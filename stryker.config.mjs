// Mutation testing with StrykerJS: `pnpm test:mutation` (CONTRIBUTING.md).
// Stryker changes the sources one small edit (mutant) at a time and runs the
// tests that cover the edit; a mutant the tests do not fail on (survived) is
// a place where the tests do not pin the behaviour down. It is slow (one test
// run per mutant), so it runs in the nightly workflow, not on pull requests.

// Stryker validates this against its schema when it starts:
// https://stryker-mutator.io/docs/stryker-js/configuration/
export default {
  mutate: [
    'packages/*/src/**/*.ts',
    'packages/*/src/**/*.tsx',
    // Tests, type tests and their fixtures
    '!packages/*/src/**/*.test.ts',
    '!packages/*/src/**/*.test.tsx',
    '!packages/*/src/**/*.spec.ts',
    '!packages/*/src/**/*.spec.tsx',
    '!packages/*/src/**/*.reference.ts',
    // Types only: nothing to mutate
    '!packages/*/src/**/*.d.ts',
    '!packages/*/src/**/types.ts',
    '!packages/*/src/**/types/**',
    // Re-exports: index.ts files and the package entry points
    '!packages/*/src/**/index.ts',
    '!packages/{adapter/src/node,ast/src/ast,common/src/common,core/src/core,react/src/react,ts-graphviz/src/ts-graphviz,ts-graphviz/src/ast}.ts',
    // Generated by `pnpm codegen` from dot.peggy
    '!packages/ast/src/dot-shim/parser/_parse.js',
  ],
  // Named, since the default (`@stryker-mutator/*` next to the core package)
  // finds nothing in pnpm's node_modules layout.
  plugins: ['@stryker-mutator/vitest-runner'],
  testRunner: 'vitest',
  vitest: {
    // The repository's vitest config minus coverage, type tests and the
    // tests tagged `process` (they start Graphviz; `pnpm test` leaves them
    // out too)
    configFile: 'vitest.mutation.config.ts',
  },
  // Only the tests that covered a mutant's location in the dry run are run
  // against it.
  coverageAnalysis: 'perTest',
  // The suite runs once per mutant; with `incremental`, a later run re-tests
  // only the mutants whose source or tests changed since the last report.
  incremental: true,
  incrementalFile: 'reports/mutation/incremental.json',
  reporters: ['clear-text', 'progress', 'html', 'json'],
  htmlReporter: { fileName: 'reports/mutation/index.html' },
  jsonReporter: { fileName: 'reports/mutation/report.json' },
  clearTextReporter: {
    // Print the survivors file by file; the html report has the diffs.
    allowColor: true,
    reportTests: false,
    reportMutants: true,
    reportScoreTable: true,
  },
  thresholds: {
    high: 90,
    low: 75,
    // A score below `break` fails the run: a little under the measured
    // score, so that the nightly job is green now and catches regressions.
    // Raise it as the tests improve.
    break: 75,
  },
  // Per test run: generous, since a mutant can turn a fast property test
  // into a slow one before it fails.
  timeoutMS: 10_000,
  timeoutFactor: 2,
  // Left out of the sandbox copy: build output and caches (Stryker does not
  // read .gitignore) and the workspaces the tests do not need. website/docs
  // stays: vitest.config.ts reads the security model from it.
  ignorePatterns: [
    'reports',
    'coverage',
    'website/build',
    'website/.docusaurus',
    'website/static/dts.json',
    'e2e',
    'examples',
    'fuzz/dist',
    'fuzz/corpus',
    'fuzz/findings',
    '**/lib',
    '**/dist',
    '**/doc',
    '.doc-examples',
    'tmp',
  ],
  tempDirName: '.stryker-tmp',
  cleanTempDir: 'always',
};
